"""Developer-only Unicode data generator; builds consume committed output.

Run: PYTHONDONTWRITEBYTECODE=1 sandbox-exec ... .venv/bin/python -B
tools/gen_unicode.py src/gen
"""
import os
from pathlib import Path
import sys
import unicodedata as ud


def ranges(values):
    result = []
    for cp in values:
        if result and result[-1][1] + 1 == cp:
            result[-1][1] = cp
        else:
            result.append([cp, cp])
    return result


def generate(destination):
    if ud.unidata_version != '16.0.0':
        raise RuntimeError('Unicode 16.0.0 is required; never refresh the pin implicitly')
    decompositions, compositions, combining, lower = [], [], [], []
    whitespace, linebreak, cased, ignorable, alphanumeric, url_delimiter = [], [], [], [], [], []
    for cp in range(0x110000):
        ch = chr(cp)
        decomposition = ud.decomposition(ch)
        # Python 3.14 exposes Hangul decomposition too. The native consumer
        # handles it algorithmically; exclude 11,172 redundant table rows.
        if decomposition and not decomposition.startswith('<') and not 0xac00 <= cp <= 0xd7a3:
            parts = [int(value, 16) for value in decomposition.split()]
            decompositions.append((cp, parts))
            if len(parts) == 2 and ud.normalize('NFC', ''.join(map(chr, parts))) == ch:
                compositions.append([*parts, cp])
        cc = ud.combining(ch)
        if cc:
            combining.append([cp, cc])
        lowered = ch.lower()
        if lowered != ch:
            lower.append((cp, list(map(ord, lowered))))
        if ch.isspace():
            whitespace.append(cp)
        if ch.isalnum():
            alphanumeric.append(cp)
        normalized=ud.normalize('NFKC',ch)
        if normalized!=ch and any(c in '/?#@:' for c in normalized):
            url_delimiter.append(cp)
        if len(('a' + ch + 'b').splitlines()) > 1:
            linebreak.append(cp)
        is_cased = ch.islower() or ch.isupper() or ud.category(ch) == 'Lt'
        if is_cased:
            cased.append(cp)
        # Probe Python's Final_Sigma context to capture Case_Ignorable exactly,
        # including characters that are both Cased and Case_Ignorable.
        if ((ch + '\u03a3').lower().endswith('\u03c3') if is_cased
                else ('A\u03a3' + ch + 'A').lower()[1] == '\u03c3'):
            ignorable.append(cp)
    header = '''/* Generated by tools/gen_unicode.py; Unicode 16.0.0. */
#ifndef COLOPHON_GEN_UNICODE_NFC_H
#define COLOPHON_GEN_UNICODE_NFC_H
#include <stddef.h>
#include <stdint.h>
#define CP_UNICODE_VERSION "16.0.0"
typedef struct { uint32_t cp, offset, length; } CpUnicodeMapping;
'''
    source = '/* Generated by tools/gen_unicode.py; Unicode 16.0.0. */\n#include "unicode_nfc.h"\n'
    for name, mappings in [('decomposition', decompositions), ('lowercase', lower)]:
        data, rows = [], []
        for cp, parts in mappings:
            rows.append([cp, len(data), len(parts)])
            data.extend(parts)
        symbol = 'cp_unicode_' + name
        header += f'extern const CpUnicodeMapping {symbol}[];\nextern const size_t {symbol}_count;\nextern const uint32_t {symbol}_data[];\n'
        source += f'const CpUnicodeMapping {symbol}[] = {{\n'
        source += ''.join('    {%s},\n' % ', '.join(hex(v) for v in row) for row in rows) + '};\n'
        source += f'const size_t {symbol}_count = sizeof({symbol}) / sizeof({symbol}[0]);\n'
        source += f'const uint32_t {symbol}_data[] = {{\n'
        source += ''.join('    ' + ', '.join(hex(v) for v in data[i:i+12]) + ',\n' for i in range(0, len(data), 12)) + '};\n'
    for name, rows, width in [('composition', sorted(compositions), 3), ('combining', combining, 2),
                              ('whitespace', ranges(whitespace), 2), ('linebreak', ranges(linebreak), 2),
                              ('cased', ranges(cased), 2), ('case_ignorable', ranges(ignorable), 2),
                              ('alphanumeric', ranges(alphanumeric), 2),
                              ('url_delimiter',ranges(url_delimiter),2)]:
        symbol = 'cp_unicode_' + name
        header += f'extern const uint32_t {symbol}[][{width}];\nextern const size_t {symbol}_count;\n'
        source += f'const uint32_t {symbol}[][{width}] = {{\n'
        source += ''.join('    {%s},\n' % ', '.join(hex(v) for v in row) for row in rows) + '};\n'
        source += f'const size_t {symbol}_count = sizeof({symbol}) / sizeof({symbol}[0]);\n'
    header += '#endif\n'
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'unicode_nfc.h').write_text(header, encoding='ascii', newline='\n')
    (destination / 'unicode_nfc.c').write_text(source, encoding='ascii', newline='\n')


if __name__ == '__main__':
    if sys.prefix == sys.base_prefix or not sys.dont_write_bytecode or os.environ.get('PYTHONDONTWRITEBYTECODE') != '1':
        raise RuntimeError('Use the project venv with -B and PYTHONDONTWRITEBYTECODE=1')
    if Path(sys.prefix).resolve() != Path(__file__).resolve().parents[1] / '.venv':
        raise RuntimeError('Use this project\'s .venv')
    if len(sys.argv) != 2:
        raise SystemExit('usage: gen_unicode.py OUTPUT_DIRECTORY')
    generate(Path(sys.argv[1]))

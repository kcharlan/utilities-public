import {pathToFileURL} from 'node:url';
import {writeFile} from 'node:fs/promises';
import {TIERS,tierHash} from '../dist/game/tiers.js';
import {buildWorld} from '../dist/game/world.js';
import {playOnce,quantile} from './flight-study.mjs';

export const defaults={gold:.4,silver:.5,bronze:.9};
const grab={pickups:()=>true};
export function samples(world,profile,seed,n,mode='standard'){
  const options={
    mode,
    capSeconds:mode==='nonstop'?2700:1200,
    extra:profile==='novice'?{}:grab
  };
  return Array.from({length:n},(_,i)=>playOnce(world,profile,seed+i,options));
}
export function deriveMedals(tier,quantiles=defaults,n=150){
  const world=buildWorld(undefined,tier);
  const ideal=playOnce(world,'ideal',1,{extra:grab});
  if(!ideal.finished||ideal.crashes||!Number.isFinite(ideal.net)){
    throw Error(`Ideal medal run failed for ${tier.id}`);
  }
  const expert=samples(world,'expert',20000,n).filter(r=>r.finished).map(r=>r.net);
  const regular=samples(world,'regular',30000,n).filter(r=>r.finished).map(r=>r.net);
  if(!expert.length||!regular.length){
    throw Error(`No finished medal derivation samples for ${tier.id}`);
  }
  const gold=Math.max(Math.ceil(ideal.net*1.02),Math.ceil(quantile(expert,quantiles.gold)));
  const silver=Math.max(gold+5,Math.ceil(quantile(regular,quantiles.silver)));
  const bronze=Math.max(silver+5,Math.ceil(quantile(regular,quantiles.bronze)));
  return {
    gold,silver,bronze,configHash:tierHash(tier),
    derived:{
      n,seeds:{ideal:1,expert:20000,regular:30000},
      quantiles:{...quantiles},idealNet:ideal.net
    }
  };
}
export function evaluate(world,table,n=150){
  const result={};
  const studies=[
    ['expert',60000,n,'standard'],
    ['regular',70000,n,'standard'],
    ['novice',80000,n,'standard'],
    ['nonstopExpert',90000,40,'nonstop'],
    ['nonstopRegular',90000,40,'nonstop']
  ];
  for(const [profile,seed,count,mode] of studies){
    const pilot=profile==='nonstopExpert'?'expert':profile==='nonstopRegular'?'regular':profile;
    const runs=samples(world,pilot,seed,count,mode);
    result[profile]=Object.fromEntries(['gold','silver','bronze'].map(medal=>[
      medal,runs.filter(run=>run.finished&&run.net<=table[medal]).length/count
    ]));
    result[profile].finish=runs.filter(run=>run.finished).length/count;
    result[profile].meanPickups=runs.reduce((sum,run)=>sum+run.collected,0)/count;
    if(mode==='nonstop'){
      const finished=runs.filter(run=>run.finished);
      result[profile].meanAttempts=finished.reduce((sum,run)=>sum+run.attempts,0)/Math.max(1,finished.length);
    }
  }
  return result;
}
export function medalGates(id,r){
  return {
    expertGold:r.expert.gold>=.25&&r.expert.gold<=.6,
    regularSilver:r.regular.silver>=.3&&r.regular.silver<=.65,
    regularBronze:r.regular.bronze>=.8,
    ...(id==='casual'?{noviceBronze:r.novice.bronze>=.45}:{}),
    nonstopExpertBronze:r.nonstopExpert.bronze>=.9
  };
}
async function main(){
  let selected=null;const overrides={};
  for(let i=2;i<process.argv.length;i++){
    const arg=process.argv[i],value=process.argv[++i];
    if(arg==='--tier')selected=value;
    else if(/^--(gold|silver|bronze)-quantile$/.test(arg))overrides[arg.slice(2,-9)]=Number(value);
    else throw Error(`Unknown option: ${arg}`);
    if(value===undefined||value.trim()===''||value.startsWith('--'))throw Error(`Missing value for ${arg}`);
  }
  if(selected!==null&&!Object.hasOwn(TIERS,selected))throw Error('Unknown tier');
  if(Object.keys(overrides).length&&!selected)throw Error('Quantile overrides require --tier');
  for(const [name,value] of Object.entries(overrides)){
    if(!Number.isFinite(value)||value<0||value>1)throw Error(`Invalid ${name} quantile`);
  }
  let previous={};
  try{
    previous=(await import('../dist/game/medals.js')).MEDALS;
  }catch(error){
    if(error.code!=='ERR_MODULE_NOT_FOUND')throw error;
  }
  const tables={...previous};
  for(const [id,tier] of Object.entries(TIERS))if(!selected||id===selected){
    const q={...defaults,...previous[id]?.derived.quantiles,...overrides};
    tables[id]=deriveMedals(tier,q);
  }
  const source=`// Generated by scripts/medals.mjs.\nexport const MEDALS = ${JSON.stringify(tables,null,2)};\n\nexport function medalFor(tier,seconds){\n  if(typeof tier!=='string'||!Object.hasOwn(MEDALS,tier)||!Number.isFinite(seconds)||seconds<=0)return null;\n  const table=MEDALS[tier];\n  return ['gold','silver','bronze'].find(medal=>seconds<=table[medal])??null;\n}\n`;
  await writeFile(new URL('../dist/game/medals.js',import.meta.url),source);
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href)main().catch(error=>{console.error(error.message);process.exitCode=1;});
